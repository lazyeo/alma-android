import { describe, expect, it } from 'vitest'
import { flightFrames } from './avatarFlight'
import {
  circleCoverage,
  circleFrames,
  circleScales,
  cubicBezierAt,
  COLLAPSE_EASING,
  COLLAPSE_MS,
  dimFrames,
  EXPAND_EASING,
  EXPAND_EASING_FALLBACK,
  EXPAND_MS,
  expandEasing,
  expandProgress,
  expandTimeline,
  FADE_COVERAGE,
  faceFlightCurve,
  faceFlightEasing,
  linearPoints,
  MIN_FADE_MS,
  recedeFrames,
  topFrames,
  TOP_OUT_MS,
} from './expandMotion'

const phone = { width: 400, height: 860 }
// Tab bar disc: 48px, centred near the bottom.
const centre = { x: 200, y: 812 }
const radius = Math.ceil(Math.hypot(200, 812))
const discRadius = 24

const COMPOSITOR_ONLY = new Set(['transform', 'opacity', 'offset', 'easing'])
const properties = (frames: Keyframe[]) =>
  frames.flatMap((frame) => Object.keys(frame))

// cubic-bezier(0.3, 0, 0.1, 1) plus a 3% bounce, as generated by the
// reference script the curve was picked with.
const REFERENCE_EXPAND =
  'linear(0,0.0033,0.0145,0.0361,0.0714,0.1239,0.1953,0.2813,0.3715,0.4563,0.5315,0.5968,0.6533,0.7022,0.7448,0.7821,0.8149,0.8439,0.8695,0.8922,0.9124,0.9302,0.9461,0.9601,0.9724,0.9832,0.9927,1.0008,1.0078,1.0137,1.0186,1.0225,1.0255,1.0278,1.0292,1.0299,1.0299,1.029,1.0272,1.0246,1.0214,1.0179,1.0141,1.0104,1.007,1.0041,1.0019,1.0005,1)'

describe('expand easing', () => {
  it('matches the reference curve sample for sample', () => {
    expect(expandEasing().replaceAll(' ', '')).toBe(REFERENCE_EXPAND)
    expect(EXPAND_EASING).toBe(expandEasing())
    expect(linearPoints(EXPAND_EASING)).toHaveLength(49)
  })

  it('evaluates the bezier by bisection', () => {
    const bezier = [0.3, 0, 0.1, 1] as const
    expect(cubicBezierAt(0, bezier)).toBeCloseTo(0, 6)
    expect(cubicBezierAt(1, bezier)).toBeCloseTo(1, 6)
    // Linear bezier is the identity.
    expect(cubicBezierAt(0.37, [0, 0, 1, 1])).toBeCloseTo(0.37, 6)
  })

  it('starts at 0, ends exactly at 1 and settles before the end', () => {
    const points = linearPoints(EXPAND_EASING)
    expect(points[0]).toBe(0)
    expect(points.at(-1)).toBe(1)
    // No visible jump on the last frame.
    expect(Math.abs(points.at(-2)! - 1)).toBeLessThan(0.005)
  })

  it('overshoots the circle scale by no more than 3.5%', () => {
    const points = linearPoints(EXPAND_EASING)
    const peak = Math.max(...points)
    expect(peak).toBeGreaterThan(1)
    expect(peak).toBeLessThanOrEqual(1.03)
    const { from } = circleScales(discRadius, radius)
    expect(from + (1 - from) * peak).toBeLessThanOrEqual(1.035)
  })

  it('rises without dipping until its single peak, then only settles', () => {
    const points = linearPoints(EXPAND_EASING)
    const peakIndex = points.indexOf(Math.max(...points))
    for (let index = 1; index <= peakIndex; index++)
      expect(points[index]).toBeGreaterThanOrEqual(points[index - 1])
    for (let index = peakIndex + 1; index < points.length; index++) {
      expect(points[index]).toBeLessThanOrEqual(points[index - 1])
      expect(points[index]).toBeGreaterThanOrEqual(1)
    }
    expect(expandProgress(0)).toBe(0)
    expect(expandProgress(1)).toBe(1)
  })
})

describe('circle geometry', () => {
  it('scales from the disc radius to the covering radius', () => {
    expect(circleScales(24, 800)).toEqual({ from: 0.03, to: 1 })
    expect(circleScales(24, 0)).toEqual({ from: 1, to: 1 })
  })

  it('measures how much of the viewport the circle covers', () => {
    expect(circleCoverage(centre, 0, phone)).toBe(0)
    expect(circleCoverage(centre, radius, phone)).toBeCloseTo(1, 3)
    // A quarter disc in the top-left corner.
    const quarter = circleCoverage({ x: 0, y: 0 }, 100, phone, 800)
    expect(quarter).toBeCloseTo((Math.PI * 100 ** 2) / 4 / (400 * 860), 3)
  })
})

describe('expandTimeline', () => {
  const open = expandTimeline({
    direction: 'open',
    centre,
    radius,
    discRadius,
    viewport: phone,
  })

  it('fades her page in once the circle covers 65% of the screen', () => {
    expect(open.duration).toBe(EXPAND_MS)
    expect(open.easing).toBe(EXPAND_EASING)
    expect(open.fadeAt).toBeGreaterThan(0)
    expect(open.fadeAt).toBeLessThan(EXPAND_MS - MIN_FADE_MS + 1)
    expect(open.fadeAt + open.fadeDuration).toBe(EXPAND_MS)
    const coverageAt = (ms: number) => {
      const scale =
        open.scale.from +
        (open.scale.to - open.scale.from) * expandProgress(ms / EXPAND_MS)
      return circleCoverage(centre, scale * radius, phone)
    }
    expect(coverageAt(open.fadeAt)).toBeGreaterThanOrEqual(FADE_COVERAGE - 0.02)
    expect(coverageAt(open.fadeAt - 4)).toBeLessThan(FADE_COVERAGE)
  })

  it('knows when the circle hides the whole old page', () => {
    expect(open.coverAt).toBeGreaterThanOrEqual(open.fadeAt)
    expect(open.coverAt).toBeLessThanOrEqual(EXPAND_MS)
  })

  it('falls back to a bezier where linear() is unsupported', () => {
    expect(
      expandTimeline({
        direction: 'open',
        centre,
        radius,
        discRadius,
        viewport: phone,
        linear: false,
      }).easing,
    ).toBe(EXPAND_EASING_FALLBACK)
  })

  it('collapses faster with an accelerating curve into the disc', () => {
    const close = expandTimeline({
      direction: 'close',
      centre,
      radius,
      discRadius,
      viewport: phone,
    })
    expect(close.duration).toBe(COLLAPSE_MS)
    expect(close.easing).toBe(COLLAPSE_EASING)
    expect(close.scale).toEqual({ from: 1, to: discRadius / radius })
    expect(close.fadeDuration).toBe(TOP_OUT_MS)
  })
})

describe('keyframes', () => {
  const timeline = expandTimeline({
    direction: 'open',
    centre,
    radius,
    discRadius,
    viewport: phone,
  })

  it('animates only transform and opacity', () => {
    for (const frames of [
      circleFrames(timeline),
      recedeFrames('open'),
      recedeFrames('close'),
      dimFrames('open'),
      dimFrames('close'),
      topFrames('open'),
      topFrames('close'),
      flightFrames(
        { left: 0, top: 0, width: 48, height: 48 },
        { left: 10, top: 10, width: 36, height: 36 },
      )!,
    ])
      for (const property of properties(frames))
        expect(COMPOSITOR_ONLY.has(property), property).toBe(true)
  })

  it('scales the circle from the disc', () => {
    expect(circleFrames(timeline)).toEqual([
      { transform: `scale(${discRadius / radius})` },
      { transform: 'scale(1)' },
    ])
  })

  it('recedes to 0.94 on open and returns on close', () => {
    expect(recedeFrames('open').at(-1)).toEqual({ transform: 'scale(0.94)' })
    expect(recedeFrames('close')[0]).toEqual({ transform: 'scale(0.94)' })
    expect(topFrames('open')[0]).toEqual({
      opacity: 0,
      transform: 'translateY(8px)',
    })
  })
})

describe('face flight curve', () => {
  const peakOf = (easing: string) => Math.max(...linearPoints(easing)) - 1

  it('caps the overshoot at 1% of the travel or 4px, whichever is smaller', () => {
    expect(faceFlightCurve(200).overshoot).toBe(0.01)
    expect(faceFlightCurve(400).overshoot).toBe(0.01)
    expect(faceFlightCurve(840).overshoot).toBeCloseTo(4 / 840, 10)
    expect(faceFlightCurve(0).overshoot).toBe(0)
    for (const travel of [38.5, 400, 839.2, 1200]) {
      const peak = peakOf(faceFlightEasing(travel))
      expect(peak * travel, `${travel}px`).toBeLessThanOrEqual(
        Math.min(0.01 * travel, 4) + 1e-3,
      )
      // A gentle settle, never a hard stop.
      expect(peak, `${travel}px`).toBeGreaterThan(0)
    }
    // The circle keeps its own 3% curve and timing.
    expect(peakOf(EXPAND_EASING)).toBeGreaterThan(0.029)
  })

  it('keeps the expand shape and lands exactly on 1', () => {
    const points = linearPoints(faceFlightEasing(839))
    expect(points[0]).toBe(0)
    expect(points.at(-1)).toBe(1)
    expect(points).toHaveLength(49)
    expect(faceFlightEasing(839, false)).toBe(EXPAND_EASING_FALLBACK)
  })
})
